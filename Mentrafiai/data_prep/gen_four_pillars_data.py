def main():
    parser = argparse.ArgumentParser(description="Generate specialized 4-pillars training corpus")
    parser.add_argument("--target_mib", type=float, default=50.0, help="Target file size in MiB (~12-15M tokens)")
    parser.add_argument("--seed", type=int, default=777)
    parser.add_argument("--out", default=str(OUT_JSONL))
    args = parser.parse_args()

    r = random.Random(args.seed)
    fns = [f for f, _ in GENERATORS]
    weights = [w for _, w in GENERATORS]
    target_bytes = args.target_mib * MIB

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    written = 0
    n = 0
    counts = {}

    print(f"Generating ~{args.target_mib:.1f} MiB of 4-Pillars Mastery Data...")
    with open(out_path, "w", encoding="utf-8") as f:
        while written < target_bytes:
            fn = r.choices(fns, weights=weights, k=1)[0]
            text = fn(r).strip()
            line = json.dumps({"text": text, "source": "four_pillars_mastery", "domain": "advisory_india"}, ensure_ascii=False) + "\n"
            f.write(line)
            written += len(line.encode("utf-8"))
            n += 1
            counts[fn.__name__] = counts.get(fn.__name__, 0) + 1
            if n % 5000 == 0:
                print(f"  {n:,} passages written | {written / MIB:.1f}/{args.target_mib:.1f} MiB", flush=True)

    print(f"\n[DONE] Wrote {n:,} 4-Pillars Mastery passages ({written / MIB:.1f} MiB) to {out_path}")
    for k, v in counts.items():
        print(f"  - {k:35}: {v:,} ({v/n*100:.1f}%)")


if __name__ == "__main__":
    main()
