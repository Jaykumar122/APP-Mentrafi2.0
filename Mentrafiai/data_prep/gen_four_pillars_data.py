def money(x):
    x = round(x)
    s = str(abs(int(x)))
    if len(s) > 3:
        head, tail = s[:-3], s[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:]); head = head[:-2]
        if head:
            parts.insert(0, head)
        s = ",".join(parts + [tail])
    return ("-" if x < 0 else "") + s


def R(x):
    return float(round(x))


def lakh(x):
    if x >= 1e7:
        return f"about ₹{x/1e7:.2f} crore"
    if x >= 1e5:
        return f"about ₹{x/1e5:.2f} lakh"
    return f"about ₹{money(x)}"


